def precision_table(group_key):
    groups = defaultdict(list)
    for row in JUDGMENTS:
        groups[group_key(row)].append(row)
    for key in sorted(groups, key=str):
        rows = groups[key]
        source = sum(row["label"] == "source" for row in rows)
        wrong = sum(row["label"] == "wrong_passage" for row in rows)
        print(
            f"{key!s:30s} n={len(rows):4d} source={source:4d} wrong={wrong:3d} "
            f"precision={source / len(rows):.3f}"
        )


def load_jsonl(path):
    with open(path) as f:
        return [json.loads(line) for line in f]


def load_artifacts():
    candidates = {
        r["id"]: r for r in load_jsonl(ARTIFACT_DIR / "case_insensitive_quotes.jsonl")
    }
    existing = {
        r["id"]: r
        for r in load_jsonl(ARTIFACT_DIR / "case_insensitive_existing_quotes.jsonl")
    }
    return candidates, existing


def agrees_with_encoder(relation):
    return relation in ("same", "overlap")


def accepted_prefix_only(prefix_words, _relation):
    return prefix_words >= TRUSTED_PREFIX_WORDS


def accepted_prefix_or_encoder(prefix_words, relation):
    return prefix_words >= TRUSTED_PREFIX_WORDS or agrees_with_encoder(relation)


def accepted_always(_prefix_words, _relation):
    return True


POLICIES = {
    "exato (artefato atual)": None,
    "ignore_case, tudo aceito": accepted_always,
    "ignore_case + prefixo>=6": accepted_prefix_only,
    "ignore_case + prefixo>=6 ou encoder": accepted_prefix_or_encoder,
}


def quote_decisions(candidates, existing, accepted):
    decisions = {}
    for udv_id, row in existing.items():
        candidate = candidates.get(udv_id)
        status = candidate["status"]["ignore_case"] if candidate else "none"
        if accepted is None:
            decisions[udv_id] = ("exact", True)
            continue
        if status == "changed":
            match = candidate["ignore_case"]
            decisions[udv_id] = (
                "relaxed",
                accepted(
                    match["prefix_words"], candidate["ignore_case_vs_embedding_top"]
                ),
            )
        else:
            decisions[udv_id] = (
                "exact",
                accepted(row["prefix_words"], row["sentence_vs_embedding_top"]),
            )
    if accepted is None:
        return decisions
    for udv_id, candidate in candidates.items():
        if candidate["status"]["ignore_case"] != "new":
            continue
        match = candidate["ignore_case"]
        decisions[udv_id] = (
            "relaxed",
            accepted(match["prefix_words"], candidate["ignore_case_vs_embedding_top"]),
        )
    return decisions


def judged_labels():
    labels = {}
    for row in JUDGMENTS:
        udv_id, variant = row["item_id"].split("#")
        labels[(udv_id, variant)] = row["label"]
    return labels


def policy_table():
    candidates, existing = load_artifacts()
    labels = judged_labels()
    print(
        f"{'política':38s} {'citações':>9s} {'julgadas':>9s} {'corretas':>9s} "
        f"{'erradas':>8s} {'precisão':>9s} {'perdidas':>9s}"
    )
    for name, accepted in POLICIES.items():
        decisions = quote_decisions(candidates, existing, accepted)
        kept = {udv_id for udv_id, (_, keep) in decisions.items() if keep}
        judged = [
            (udv_id, labels[(udv_id, variant)])
            for udv_id, (variant, keep) in decisions.items()
            if keep and (udv_id, variant) in labels
        ]
        source = sum(1 for _, label in judged if label == "source")
        wrong = sum(1 for _, label in judged if label == "wrong_passage")
        lost = sum(
            1
            for udv_id, (variant, keep) in decisions.items()
            if not keep and labels.get((udv_id, variant)) == "source"
        )
        precision = source / len(judged) if judged else float("nan")
        print(
            f"{name:38s} {len(kept):9d} {len(judged):9d} {source:9d} "
            f"{wrong:8d} {precision:9.3f} {lost:9d}"
        )


def stratified_precision_of_current_artifact():
    _, existing = load_artifacts()
    labels = judged_labels()
    strata = {"prefixo < 6 palavras": [], "prefixo >= 6 palavras": []}
    for udv_id, row in existing.items():
        key = (
            "prefixo >= 6 palavras"
            if row["prefix_words"] >= TRUSTED_PREFIX_WORDS
            else "prefixo < 6 palavras"
        )
        strata[key].append(udv_id)
    estimate = 0.0
    for name, ids in strata.items():
        judged = [labels[(i, "exact")] for i in ids if (i, "exact") in labels]
        source = sum(1 for label in judged if label == "source")
        rate = source / len(judged) if judged else float("nan")
        estimate += rate * len(ids)
        print(
            f"{name:22s} registros={len(ids):4d} julgados={len(judged):4d} precisão={rate:.3f}"
        )
    total = sum(len(ids) for ids in strata.values())
    print(f"estimativa estratificada do artefato atual: {estimate / total:.3f}")
    print(f"registros errados estimados: {round(total - estimate)} de {total}")


def coverage_of_relaxed_matches():
    candidates, _ = load_artifacts()
    labels = judged_labels()
    counter = Counter()
    for udv_id, candidate in candidates.items():
        if candidate["status"]["ignore_case"] != "new":
            continue
        label = labels.get((udv_id, "relaxed"))
        counter[
            (candidate["ignore_case"]["prefix_words"] >= TRUSTED_PREFIX_WORDS, label)
        ] += 1
    for key in sorted(counter, key=str):
        print(f"prefixo>=6={key[0]!s:5s} {key[1]!s:14s} {counter[key]:4d}")


